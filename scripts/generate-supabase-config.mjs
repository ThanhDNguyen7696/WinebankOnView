import { readFile, writeFile } from "node:fs/promises";

const envPath = process.argv[2] || ".env.local";
let contents;

try {
  contents = await readFile(envPath, "utf8");
} catch {
  contents = "";
}

const fileValues = Object.fromEntries(
  contents
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const separator = line.indexOf("=");
      return separator === -1
        ? [line, ""]
        : [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
    })
);

const supabaseUrl = process.env.SUPABASE_URL || fileValues.SUPABASE_URL;
const anonKey = process.env.SUPABASE_ANON_KEY || fileValues.SUPABASE_ANON_KEY;

if (!supabaseUrl || !anonKey || supabaseUrl.includes("YOUR_PROJECT") || anonKey.includes("YOUR_SUPABASE")) {
  throw new Error(
    `Set SUPABASE_URL and SUPABASE_ANON_KEY in ${envPath} (copy .env.example to .env.local first).`
  );
}

const output = `// Generated by scripts/generate-supabase-config.mjs. Do not edit or commit.
export const SUPABASE_URL = ${JSON.stringify(supabaseUrl)};
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)};

export const MENU_BUCKET = "menus";
export const MENU_PATH = "food/current-menu.pdf";

export function hasSupabaseConfig() {
  return Boolean(SUPABASE_URL && SUPABASE_ANON_KEY);
}
`;

await writeFile("JS/supabase-config.js", output, "utf8");
console.log(`Generated JS/supabase-config.js from ${envPath}`);
